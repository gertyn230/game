/// Малює покращені лікарські трави
pub fn draw_modern_herb(sx: f32, sy: f32, u: f32, now: f64, dead: bool) {
    if !dead {
        let sway = ((now * 4.0).sin() * 0.5) as f32;

        // Стебла (різної висоти)
        rc(sx, sy, u, 4.0 + sway, 8.0, 1.0, 5.0, hx(0x66cc66));
        rc(sx, sy, u, 6.0 - sway * 0.5, 7.0, 1.0, 6.0, hx(0x66cc66));
        rc(sx, sy, u, 8.0 + sway * 0.7, 9.0, 1.0, 4.0, hx(0x66cc66));
        rc(sx, sy, u, 10.0 - sway, 8.0, 1.0, 5.0, hx(0x66cc66));

        // Листя на стеблах
        rc(sx, sy, u, 3.0 + sway, 10.0, 2.0, 1.0, hx(0x55bb55));
        rc(sx, sy, u, 5.0 - sway * 0.5, 9.0, 2.0, 1.0, hx(0x55bb55));
        rc(sx, sy, u, 9.0 - sway, 10.0, 2.0, 1.0, hx(0x55bb55));

        // Жовті квітки на верху (лікувальні)
        rc(sx, sy, u, 4.0 + sway, 6.0, 1.0, 1.0, hx(0xffff99));
        rc(sx, sy, u, 6.0 - sway * 0.5, 5.0, 1.0, 1.0, hx(0xffff99));
        rc(sx, sy, u, 10.0 - sway, 6.0, 1.0, 1.0, hx(0xffff99));
        // Пилок (блискучий центр)
        rc(sx, sy, u, 6.0 - sway * 0.5, 5.0, 1.0, 1.0, hx(0xffffcc));
    }
}

/// Малює покращене вогнище з анімацією вогню
pub fn draw_modern_fire(sx: f32, sy: f32, u: f32, now: f64) {
    // Тінь від дров
    draw_rectangle(
        sx - 5.0 * u,
        sy + 3.0 * u,
        10.0 * u,
        1.0 * u,
        Color::new(0.0, 0.0, 0.0, 0.2),
    );

    // Дрова (кілька колод)
    rc(sx, sy, u, -5.0, 1.0, 10.0, 2.0, hx(0x6b4423));
    rc(sx, sy, u, -4.0, -0.5, 8.0, 1.5, hx(0x5a3a1a));
    rc(sx, sy, u, -3.0, 2.0, 6.0, 1.5, hx(0x5a3a1a));

    // Вогонь (анімований - коливається)
    let h = 3.0 + ((now * 8.0) as i64 % 3) as f32;
    let flicker = ((now * 12.0).sin() * 0.3) as f32;

    // Основа вогню (червоно-помаранчева)
    rc(sx, sy, u, -2.5, -h + flicker, 5.0, h + 1.0, hx(0xf08a24));
    // Центр вогню (яскраво-жовтий)
    rc(sx, sy, u, -1.5, -h + 1.0 + flicker, 3.0, h - 1.0, hx(0xffd54a));
    // Верхівка вогню (яскраво-біла)
    rc(sx, sy, u, -0.5, -h + flicker, 1.0, 1.5, hx(0xffffff));

    // Іскри (випадкові)
    let spark_offset = ((now * 10.0) as i64 % 5) as f32;
    rc(sx, sy, u, -3.0, -h - 1.0 - spark_offset, 0.5, 0.5, hx(0xffd54a));
    rc(sx, sy, u, 2.0, -h - 0.5 - spark_offset * 0.7, 0.5, 0.5, hx(0xffd54a));

    // Світло від вогню (м'яке сяйво)
    draw_circle(
        sx,
        sy - h * u * 0.5,
        (h + 3.0) * u,
        Color::new(1.0, 0.6, 0.2, 0.1),
    );
}

/// Малює покращену піч
pub fn draw_modern_furnace(sx: f32, sy: f32, u: f32, now: f64) {
    // Тінь від печі
    draw_rectangle(
        sx - 6.0 * u,
        sy + 5.0 * u,
        12.0 * u,
        2.5 * u,
        Color::new(0.0, 0.0, 0.0, 0.3),
    );

    // Основа печі (камінь з текстурою)
    rc(sx, sy, u, -5.0, -4.0, 10.0, 9.0, hx(0x6e6e76));
    rc(sx, sy, u, -5.0, -4.0, 10.0, 2.0, hx(0x8d8d96)); // верх (світліший)
    rc(sx, sy, u, -5.0, 3.0, 10.0, 2.0, hx(0x55555c)); // низ (темніший)

    // Текстура каменю
    rc(sx, sy, u, -4.0, -2.0, 1.0, 1.0, hx(0x8d8d96));
    rc(sx, sy, u, 2.0, 0.0, 1.0, 1.0, hx(0x8d8d96));
    rc(sx, sy, u, -2.0, 3.0, 1.0, 1.0, hx(0x55555c));

    // Отвір печі (прямокутний)
    rc(sx, sy, u, -2.5, 0.0, 5.0, 4.0, hx(0x222222));
    // Рамка отвору
    rc(sx, sy, u, -3.0, -0.5, 6.0, 0.5, hx(0x8d8d96));

    // Вогонь всередині (анімований)
    let flicker = 2.0 - ((now * 6.0) as i64 % 2) as f32;
    rc(sx, sy, u, -1.5, flicker, 3.0, 2.0, hx(0xf08a24));
    rc(sx, sy, u, -0.5, flicker, 1.0, 1.5, hx(0xffd54a));

    // Світло від печі
    draw_circle(
        sx,
        sy + 2.0 * u,
        4.0 * u,
        Color::new(1.0, 0.5, 0.1, 0.12),
    );

    // Димар (дим)
    if ((now * 2.0) as i64 % 3) == 0 {
        rc(sx, sy, u, -1.0, -6.0, 2.0, 1.5, Color::new(0.6, 0.6, 0.6, 0.3));
        rc(sx, sy, u, 0.0, -8.0, 1.5, 1.5, Color::new(0.7, 0.7, 0.7, 0.2));
    }
}

/// Малює покращений будинок
pub fn draw_modern_house(sx: f32, sy: f32, u: f32, _now: f64) {
    // Тінь будинку
    draw_rectangle(
        sx + 1.0 * u,
        sy + 14.0 * u,
        14.0 * u,
        2.5 * u,
        Color::new(0.0, 0.0, 0.0, 0.25),
    );

    // Стіни (з текстурою дерева)
    rc(sx, sy, u, 2.0, 6.0, 12.0, 9.0, hx(0xc97b4a));
    rc(sx, sy, u, 2.0, 12.0, 12.0, 3.0, hx(0xa8623a)); // низ темніший

    // Дошки (вертикальні лінії)
    for x in [4.0, 7.0, 10.0] {
        rc(sx, sy, u, x, 6.0, 0.5, 9.0, hx(0xa8623a));
    }

    // Дах (червона черепиця)
    rc(sx, sy, u, 1.0, 2.0, 14.0, 5.0, hx(0x8a3b2e));
    rc(sx, sy, u, 1.0, 6.0, 14.0, 1.0, hx(0x6e2d23)); // край даху
    rc(sx, sy, u, 3.0, 3.0, 10.0, 1.0, hx(0xb04a3a)); // світліша частина

    // Черепиця (текстура)
    for py in [3.0, 4.5] {
        for px in [2.0, 5.0, 8.0, 11.0] {
            rc(sx, sy, u, px, py, 1.5, 0.5, hx(0x6e2d23));
        }
    }

    // Двері (коричневі)
    rc(sx, sy, u, 7.0, 10.0, 3.0, 5.0, hx(0x3b2a1a));
    // Ручка дверей
    rc(sx, sy, u, 9.0, 12.0, 0.5, 0.5, hx(0xd4a574));

    // Вікна (блакитні, відображають небо)
    rc(sx, sy, u, 4.0, 8.0, 2.0, 2.0, hx(0xbfe3f5));
    rc(sx, sy, u, 11.0, 8.0, 2.0, 2.0, hx(0xbfe3f5));

    // Рами вікон (хрест)
    rc(sx, sy, u, 4.9, 8.0, 0.2, 2.0, hx(0x3b2a1a));
    rc(sx, sy, u, 4.0, 8.9, 2.0, 0.2, hx(0x3b2a1a));
    rc(sx, sy, u, 11.9, 8.0, 0.2, 2.0, hx(0x3b2a1a));
    rc(sx, sy, u, 11.0, 8.9, 2.0, 0.2, hx(0x3b2a1a));

    // Димохід
    rc(sx, sy, u, 10.0, 0.0, 2.0, 3.0, hx(0x6e6e76));
    rc(sx, sy, u, 10.0, 0.0, 2.0, 0.5, hx(0x8d8d96)); // верх
}

/// Малює ресурси на землі (палиці, камінці, волокно)
pub fn draw_modern_ground_item(sx: f32, sy: f32, u: f32, kind: Kind) {
    match kind {
        Kind::Stick => {
            // Палиці (кілька)
            rc(sx, sy, u, 3.0, 10.0, 8.0, 1.0, hx(0x8b5a2b));
            rc(sx, sy, u, 5.0, 8.0, 5.0, 1.0, hx(0x8b5a2b));
            rc(sx, sy, u, 3.0, 10.0, 3.0, 1.0, hx(0xb07a45)); // світліша частина
            rc(sx, sy, u, 5.0, 8.0, 2.0, 1.0, hx(0xb07a45));
        }
        Kind::Pebble => {
            // Камінці (кілька різних розмірів)
            rc(sx, sy, u, 4.0, 10.0, 4.0, 3.0, hx(0x9a9aa4));
            rc(sx, sy, u, 5.0, 10.0, 2.0, 1.0, hx(0xcfcfd8)); // блик
            rc(sx, sy, u, 9.0, 9.0, 3.0, 2.0, hx(0x9a9aa4));
            rc(sx, sy, u, 10.0, 9.0, 1.0, 1.0, hx(0xcfcfd8)); // блик
            rc(sx, sy, u, 6.0, 12.0, 2.0, 1.0, hx(0x8a8a90)); // маленький камінчик
        }
        Kind::Fiber => {
            // Волокна (зелені стебла)
            rc(sx, sy, u, 5.0, 7.0, 1.0, 6.0, hx(0x9ad06a));
            rc(sx, sy, u, 7.0, 6.0, 1.0, 7.0, hx(0xb8e68a)); // світліше волокно
            rc(sx, sy, u, 9.0, 8.0, 1.0, 5.0, hx(0x9ad06a));
            // Насіння на верху
            rc(sx, sy, u, 6.0, 6.0, 1.0, 1.0, hx(0xe8d98a));
            rc(sx, sy, u, 8.0, 5.0, 1.0, 1.0, hx(0xe8d98a));
        }
        _ => {}
    }
}
