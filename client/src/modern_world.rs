/// Малює покращене дерево з більшою деталізацією
pub fn draw_modern_tree(sx: f32, sy: f32, u: f32, now: f64, dead: bool) {
    // Тінь дерева
    draw_rectangle(
        sx + 3.0 * u,
        sy + 13.0 * u,
        10.0 * u,
        2.5 * u,
        Color::new(0.0, 0.0, 0.0, 0.25),
    );

    if dead {
        // Пень
        rc(sx, sy, u, 6.0, 10.0, 4.0, 4.0, hx(0x6b4423));
        rc(sx, sy, u, 6.0, 10.0, 4.0, 1.0, hx(0x9a6b3a));
        rc(sx, sy, u, 7.0, 11.0, 2.0, 2.0, hx(0x4d2f17)); // темне кільце
    } else {
        // Стовбур (з текстурою кори)
        rc(sx, sy, u, 7.0, 8.0, 3.0, 7.0, hx(0x6b4423));
        rc(sx, sy, u, 9.0, 8.0, 1.0, 7.0, hx(0x4d2f17)); // тінь
        rc(sx, sy, u, 7.0, 9.0, 1.0, 1.0, hx(0x4d2f17)); // текстура
        rc(sx, sy, u, 8.0, 11.0, 1.0, 1.0, hx(0x4d2f17));
        rc(sx, sy, u, 7.0, 13.0, 1.0, 1.0, hx(0x4d2f17));

        // Крона (багатошарова)
        // Нижній шар
        rc(sx, sy, u, 3.0, 7.0, 10.0, 3.0, hx(0x256427));
        // Середній шар
        rc(sx, sy, u, 2.0, 3.0, 12.0, 6.0, hx(0x2f7d32));
        // Верхній шар (світліший)
        rc(sx, sy, u, 4.0, 1.0, 8.0, 4.0, hx(0x3f9a43));
        // Блики
        rc(sx, sy, u, 5.0, 2.0, 3.0, 2.0, hx(0x62b865));
        rc(sx, sy, u, 9.0, 3.0, 2.0, 1.0, hx(0x62b865));

        // Гілки (анімовані вітром)
        let sway = ((now * 2.0).sin() * 0.5) as f32;
        rc(sx, sy, u, 3.0 + sway, 5.0, 2.0, 1.0, hx(0x6b4423));
        rc(sx, sy, u, 11.0 - sway, 6.0, 2.0, 1.0, hx(0x6b4423));
    }
}

/// Малює покращений камінь/руду
pub fn draw_modern_rock(sx: f32, sy: f32, u: f32, node_kind: Kind, dead: bool) {
    // Тінь
    draw_rectangle(
        sx + 2.0 * u,
        sy + 13.0 * u,
        12.0 * u,
        2.5 * u,
        Color::new(0.0, 0.0, 0.0, 0.25),
    );

    if dead {
        // Залишки каменю
        rc(sx, sy, u, 5.0, 12.0, 6.0, 2.0, hx(0x77777f));
        rc(sx, sy, u, 6.0, 11.0, 4.0, 1.0, hx(0x8d8d96));
    } else {
        // Основа каменю (багатокутник)
        rc(sx, sy, u, 2.0, 7.0, 12.0, 7.0, hx(0x6d6d76)); // тінь
        rc(sx, sy, u, 3.0, 5.0, 9.0, 6.0, hx(0x8d8d96)); // основа
        rc(sx, sy, u, 4.0, 5.0, 4.0, 3.0, hx(0xb4b4be)); // блик
        rc(sx, sy, u, 2.0, 12.0, 12.0, 2.0, hx(0x55555c)); // низ

        // Текстура каменю
        rc(sx, sy, u, 5.0, 7.0, 1.0, 1.0, hx(0x6d6d76));
        rc(sx, sy, u, 8.0, 9.0, 1.0, 1.0, hx(0x6d6d76));
        rc(sx, sy, u, 10.0, 6.0, 1.0, 1.0, hx(0xb4b4be));

        // Вкраплення руди
        if node_kind != Kind::Rock {
            let (c1, c2) = match node_kind {
                Kind::Coal => (0x1d1d22, 0x1d1d22),
                Kind::CuOre => (0xd9823a, 0x4fb09a), // мідь (помаранчево-бірюзова)
                Kind::FeOre => (0xc4623a, 0x8a4a2a), // залізо (червонувато-коричнева)
                Kind::AgOre => (0xe0e0e8, 0xa0a0a8), // срібло (сріблясто-сіра)
                Kind::AuOre => (0xffdd00, 0xffaa00), // золото (жовто-помаранчева)
                _ => (0x9a9aa4, 0x7a7a7c),
            };
            // Великі вкраплення
            rc(sx, sy, u, 4.0, 6.0, 2.0, 2.0, hx(c1));
            rc(sx, sy, u, 9.0, 5.0, 3.0, 2.0, hx(c1));
            rc(sx, sy, u, 6.0, 10.0, 3.0, 2.0, hx(c1));
            // Маленькі вкраплення
            rc(sx, sy, u, 10.0, 10.0, 2.0, 2.0, hx(c2));
            rc(sx, sy, u, 3.0, 9.0, 1.0, 1.0, hx(c2));
        }
    }
}

/// Малює покращений кущ
pub fn draw_modern_bush(sx: f32, sy: f32, u: f32, now: f64, dead: bool) {
    // Тінь
    draw_rectangle(
        sx + 2.0 * u,
        sy + 13.0 * u,
        12.0 * u,
        2.0 * u,
        Color::new(0.0, 0.0, 0.0, 0.22),
    );

    if dead {
        // Сухий кущ
        rc(sx, sy, u, 5.0, 11.0, 6.0, 3.0, hx(0x3f8f3a));
        rc(sx, sy, u, 6.0, 10.0, 4.0, 1.0, hx(0x2a6e2e));
    } else {
        // Анімація вітру
        let sway = ((now * 3.0).sin() * 0.3) as f32;

        // Основа куща (темніша)
        rc(sx, sy, u, 2.0, 8.0, 12.0, 6.0, hx(0x2a6e2e));
        // Середній шар
        rc(sx, sy, u, 3.0 + sway, 5.0, 10.0, 6.0, hx(0x3f9a43));
        // Верхній шар (світліший)
        rc(sx, sy, u, 4.0 + sway, 5.0, 4.0, 2.0, hx(0x62b865));
        rc(sx, sy, u, 9.0 - sway, 6.0, 3.0, 2.0, hx(0x62b865));

        // Ягоди на кущі
        for (ox, oy) in [(5.0, 8.0), (10.0, 10.0), (8.0, 6.0)] {
            rc(sx, sy, u, ox + sway, oy, 2.0, 2.0, hx(0xd94f4f));
            // Блик на ягоді
            rc(sx, sy, u, ox + sway, oy, 1.0, 1.0, hx(0xff6f6f));
        }
    }
}

/// Малює покращений кущ ягід
pub fn draw_modern_berry_bush(sx: f32, sy: f32, u: f32, now: f64, dead: bool) {
    // Тінь
    draw_rectangle(
        sx + 2.0 * u,
        sy + 13.0 * u,
        12.0 * u,
        2.0 * u,
        Color::new(0.0, 0.0, 0.0, 0.22),
    );

    if dead {
        // Зібраний кущ
        rc(sx, sy, u, 5.0, 11.0, 6.0, 3.0, hx(0x3f8f3a));
    } else {
        let sway = ((now * 2.5).sin() * 0.4) as f32;

        // Листя
        rc(sx, sy, u, 2.0, 8.0, 12.0, 6.0, hx(0x3f9a43));
        rc(sx, sy, u, 3.0 + sway, 5.0, 10.0, 6.0, hx(0x62b865));

        // Багато ягід (різного розміру)
        for (ox, oy, size) in [
            (4.0, 7.0, 2.0), (8.0, 9.0, 2.0), (10.0, 6.0, 2.0), (6.0, 10.0, 2.0),
            (5.0, 5.0, 1.0), (11.0, 8.0, 1.0), (7.0, 6.0, 1.0)
        ] {
            rc(sx, sy, u, ox + sway * 0.5, oy, size, size, hx(0xff3366));
            // Блик
            rc(sx, sy, u, ox + sway * 0.5, oy, (size * 0.5) as f32, (size * 0.5) as f32, hx(0xff6688));
        }
    }
}

